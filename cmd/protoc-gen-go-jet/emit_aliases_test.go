// TestJsonbFilterPaths — direct unit coverage for the helper that
// assembles the auto-registered FilterFields entries for both
// `Column.jsonb_indexed_paths` and `OneofColumn.jsonb_indexed_paths`.
// Integration tests via ClusterLike exercise both branches end-to-
// end, but the helper itself deserves focused tests so a regression
// in shape / ordering is caught without a testcontainer.
func TestJsonbFilterPaths(t *testing.T) {
	t.Parallel()

	t.Run("column paths only", func(t *testing.T) {
		t.Parallel()
		p := &ResourcePlan{
			Columns: []ColumnPlan{
				{DBName: "config", Kind: KindJSONBProto, JSONBIndexedPaths: []string{"api_key", "nested.timeout"}},
			},
		}
		got := jsonbFilterPaths(p)
		assert.Equal(t, []jsonbFilterPath{
			{Key: "config.api_key", Expr: "config->>'api_key'"},
			{Key: "config.nested.timeout", Expr: "config->'nested'->>'timeout'"},
		}, got)
	})

	t.Run("oneof paths only", func(t *testing.T) {
		t.Parallel()
		p := &ResourcePlan{
			OneofColumns: []OneofColumnPlan{
				{
					BaseName:          "cloud",
					KindColumn:        "cloud_kind",
					JSONColumn:        "cloud",
					JSONBIndexedPaths: []string{"accountId"},
				},
			},
		}
		got := jsonbFilterPaths(p)
		assert.Equal(t, []jsonbFilterPath{
			{Key: "cloud.accountId", Expr: "cloud->>'accountId'"},
		}, got)
	})

	t.Run("both column + oneof paths — columns first, oneofs second", func(t *testing.T) {
		t.Parallel()
		// Emission order matters: column entries precede oneof
		// entries in the generated FilterFields map literal. Order
		// within each group follows declaration order in the plan.
		p := &ResourcePlan{
			Columns: []ColumnPlan{
				{DBName: "spec", Kind: KindJSONBProto, JSONBIndexedPaths: []string{"version"}},
				{DBName: "attrs", Kind: KindJSONBStrMap, JSONBIndexedPaths: []string{"env"}},
			},
			OneofColumns: []OneofColumnPlan{
				{BaseName: "cloud", JSONColumn: "cloud", JSONBIndexedPaths: []string{"accountId"}},
			},
		}
		got := jsonbFilterPaths(p)
		require.Len(t, got, 3)
		assert.Equal(t, "spec.version", got[0].Key)
		assert.Equal(t, "attrs.env", got[1].Key)
		assert.Equal(t, "cloud.accountId", got[2].Key, "oneof path must follow column paths")
	})

	t.Run("no paths — nil result", func(t *testing.T) {
		t.Parallel()
		p := &ResourcePlan{
			Columns: []ColumnPlan{
				{DBName: "name", Kind: KindScalar, JSONBIndexedPaths: nil},
			},
		}
		got := jsonbFilterPaths(p)
		assert.Nil(t, got)
	})

	t.Run("column with empty paths list is equivalent to no paths", func(t *testing.T) {
		t.Parallel()
		p := &ResourcePlan{
			Columns: []ColumnPlan{
				{DBName: "config", Kind: KindJSONBProto, JSONBIndexedPaths: []string{}},
			},
		}
		got := jsonbFilterPaths(p)
		assert.Nil(t, got)
	})
}

