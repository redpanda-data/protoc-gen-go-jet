// TestRenderAliases_FilterFieldsIncludesCursorCapable pins the
// filterability surface: the generated <Prefix>FilterFields() must
// list every column whose kind has a cursor codec (scalar string/
// bool/int, timestamp, enum-as-text, duration) and must exclude the
// ones the grammar can't express (JSONB, TEXT[], BYTEA, synthesized).
// Excluded kinds would be rejected by the translator at query time
// anyway — hiding them at generation time stops callers from
// writing filters that can only fail.
func TestRenderAliases_FilterFieldsIncludesCursorCapable(t *testing.T) {
	t.Parallel()
	got := renderAliases(aliasFixture(), "x.Widget")

	require.Contains(t, got, "func WidgetFilterFields() aipjet.FilterFields {")
	require.Contains(t, got, `"name": WidgetTable.Name,`)
	require.Contains(t, got, `"display_name": WidgetTable.DisplayName,`)
	require.Contains(t, got, `"created_at": WidgetTable.CreatedAt,`)
	require.Contains(t, got, `"updated_at": WidgetTable.UpdatedAt,`)

	// tenant_id is synthesized — must never appear as a filter key,
	// letting a caller filter by tenant_id would bypass the service's
	// implicit scoping.
	assert.NotContains(t, got, `"tenant_id"`)
}

// TestRenderAliases_FilterFieldsExcludesUnbindable covers the kinds
// the filter grammar cannot express — JSONB, BYTEA. They must NOT
// appear in FilterFields (the translator would reject them anyway;
// exposing them at generation time is a UX trap). Durations ARE
// filterable (BIGINT ns via integerOp) and stay in. Repeated-text
// kinds (TEXT[]) also bind now — they route through stringArrayOp
// and compile to `value = ANY(col)`.
func TestRenderAliases_FilterFieldsExcludesUnbindable(t *testing.T) {
	t.Parallel()
	p := aliasFixture()
	p.Columns = append(p.Columns,
		ColumnPlan{DBName: "metadata", JetFieldName: "Metadata", Kind: KindJSONBProto, JetGoType: "string"},
		ColumnPlan{DBName: "scopes", JetFieldName: "Scopes", Kind: KindRepeatedText, JetGoType: "pq.StringArray"},
		ColumnPlan{DBName: "ttl", JetFieldName: "Ttl", Kind: KindDuration, JetGoType: "int64"},
		ColumnPlan{DBName: "payload", JetFieldName: "Payload", Kind: KindScalar, JetGoType: "[]byte"},
	)
	got := renderAliases(p, "x.Widget")

	require.Contains(t, got, "func WidgetFilterFields() aipjet.FilterFields {")
	assert.NotContains(t, got, `"metadata"`)
	assert.NotContains(t, got, `"payload"`)
	// Duration binds through integerOp.
	assert.Contains(t, got, `"ttl": WidgetTable.Ttl,`)
	// Repeated text binds through stringArrayOp.
	assert.Contains(t, got, `"scopes": WidgetTable.Scopes,`)
}

