// funcBody slices the generated source between the opening `{` of the
// named function and its matching closing `}` at column 0. Brittle if
// the generator ever emits nested `}` at column 0, but the aliases.go
// emitter doesn't.
func funcBody(t *testing.T, source, header string) string {
	t.Helper()
	start := strings.Index(source, header)
	require.Greaterf(t, start, -1, "function header %q not found in source", header)
	rest := source[start:]
	end := strings.Index(rest, "\n}\n")
	require.Greater(t, end, 0)
	return rest[:end]
}

