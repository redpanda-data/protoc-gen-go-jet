// TestFilterableJetFields pins the filtering-surface decision table
// directly, without going through renderAliases. Keeps the gate rule
// visible next to the kinds whose filterability status it pins.
func TestFilterableJetFields(t *testing.T) {
	t.Parallel()
	p := &ResourcePlan{
		Columns: []ColumnPlan{
			// Synthesized never filterable, even if the kind would be.
			{DBName: "tenant_id", JetFieldName: "TenantID", Kind: KindSynthesized, JetGoType: "string", Synthesized: true},

			// Scalars pass — except the []byte variant (no cursor codec).
			{DBName: "name", JetFieldName: "Name", Kind: KindScalar, JetGoType: "string"},
			{DBName: "enabled", JetFieldName: "Enabled", Kind: KindScalar, JetGoType: "bool"},
			{DBName: "priority", JetFieldName: "Priority", Kind: KindScalar, JetGoType: "int32"},
			{DBName: "count", JetFieldName: "Count", Kind: KindScalar, JetGoType: "int64"},
			{DBName: "blob", JetFieldName: "Blob", Kind: KindScalar, JetGoType: "[]byte"},

			// Timestamps and enums pass.
			{DBName: "created_at", JetFieldName: "CreatedAt", Kind: KindTimestamp, JetGoType: "time.Time"},
			{DBName: "type", JetFieldName: "Type", Kind: KindEnumAsText, JetGoType: "string"},

			// Durations ARE filterable — stored as BIGINT ns, bind through
			// integerOp, accept bare int or duration("5m").
			{DBName: "ttl", JetFieldName: "Ttl", Kind: KindDuration, JetGoType: "int64"},

			// Repeated-text kinds participate via the array path —
			// `zones = "us-west-1"` compiles to `'us-west-1' = ANY(zones)`.
			{DBName: "scopes", JetFieldName: "Scopes", Kind: KindRepeatedText, JetGoType: "pq.StringArray"},
			{DBName: "roles", JetFieldName: "Roles", Kind: KindRepeatedEnum, JetGoType: "pq.StringArray"},

			// Kinds the filter grammar can't express are excluded.
			{DBName: "metadata", JetFieldName: "Metadata", Kind: KindJSONBProto, JetGoType: "string"},
			{DBName: "tags", JetFieldName: "Tags", Kind: KindJSONBStrMap, JetGoType: "string"},
			{DBName: "events", JetFieldName: "Events", Kind: KindJSONBProtoList, JetGoType: "string"},
		},
	}
	got := filterableJetFields(p)
	wantKeys := []string{"name", "enabled", "priority", "count", "created_at", "type", "ttl", "scopes", "roles"}

	haveKeys := make([]string, 0, len(got))
	for _, f := range got {
		haveKeys = append(haveKeys, f.Key)
	}
	assert.Equal(t, wantKeys, haveKeys, "filterable surface mismatch")

	// Declaration order preserved — the emitter relies on this to keep
	// generated aliases.go byte-deterministic across runs.
	assert.Equal(t, "Name", got[0].JetField)
	assert.Equal(t, "Roles", got[len(got)-1].JetField)
}

